-- Dedicated private schema for the server-side VetStock application.
-- Apply only to the VetStock project; never to an unrelated database.
CREATE SCHEMA IF NOT EXISTS vetstock;
REVOKE ALL ON SCHEMA vetstock FROM PUBLIC, anon, authenticated;
SET LOCAL search_path TO vetstock, pg_catalog;

CREATE TABLE IF NOT EXISTS users(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL, display_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('admin','employee')),
  password_hash TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
  alerts INTEGER NOT NULL DEFAULT 1 CHECK(alerts IN (0,1)), created_at TEXT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_casefold ON users (lower(username));
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS medicines(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, strength TEXT NOT NULL DEFAULT '', form TEXT NOT NULL DEFAULT '', barcode TEXT UNIQUE,
  pack_size BIGINT NOT NULL CHECK(pack_size>0), price_pack BIGINT, price_unit BIGINT,
  threshold BIGINT NOT NULL DEFAULT 0 CHECK(threshold>=0),
  threshold_mode TEXT NOT NULL CHECK(threshold_mode IN ('units','boxes')),
  expiry_days BIGINT NOT NULL DEFAULT 90 CHECK(expiry_days>=0), active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS lots(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, medicine_id BIGINT NOT NULL REFERENCES medicines(id),
  batch TEXT NOT NULL, expiry TEXT, boxes BIGINT NOT NULL CHECK(boxes>=0),
  loose BIGINT NOT NULL CHECK(loose>=0), received_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS suppliers(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '', address TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS orders(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  status TEXT NOT NULL DEFAULT 'open', notes TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS order_lines(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
  medicine_id BIGINT NOT NULL REFERENCES medicines(id), boxes BIGINT NOT NULL CHECK(boxes>0),
  received BIGINT NOT NULL DEFAULT 0 CHECK(received>=0));
CREATE TABLE IF NOT EXISTS receipts(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, medicine_id BIGINT NOT NULL REFERENCES medicines(id),
  lot_id BIGINT NOT NULL REFERENCES lots(id), order_line_id BIGINT REFERENCES order_lines(id),
  boxes BIGINT NOT NULL, loose BIGINT NOT NULL, user_id BIGINT NOT NULL REFERENCES users(id), created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS supplier_invoices(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  invoice_no TEXT NOT NULL, total BIGINT NOT NULL CHECK(total>=0), due_date TEXT, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS supplier_payments(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, invoice_id BIGINT NOT NULL REFERENCES supplier_invoices(id),
  amount BIGINT NOT NULL CHECK(amount>0), method TEXT NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(id), created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS supplier_invoice_files(
  invoice_id BIGINT PRIMARY KEY REFERENCES supplier_invoices(id), filename TEXT NOT NULL, content BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS sales(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_name TEXT NOT NULL DEFAULT '',
  subtotal BIGINT NOT NULL, discount BIGINT NOT NULL, total BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active', user_id BIGINT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL, void_reason TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS sale_lines(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sale_id BIGINT NOT NULL REFERENCES sales(id),
  medicine_id BIGINT NOT NULL REFERENCES medicines(id), medicine_name TEXT NOT NULL,
  kind TEXT NOT NULL CHECK(kind IN ('box','unit')), qty BIGINT NOT NULL CHECK(qty>0),
  unit_price BIGINT NOT NULL, total BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS sale_allocations(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, line_id BIGINT NOT NULL REFERENCES sale_lines(id),
  lot_id BIGINT NOT NULL REFERENCES lots(id), kind TEXT NOT NULL, qty BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS sale_payments(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sale_id BIGINT NOT NULL REFERENCES sales(id),
  amount BIGINT NOT NULL CHECK(amount>0), method TEXT NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(id), created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS audit(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT REFERENCES users(id),
  action TEXT NOT NULL, details TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(
  token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS login_attempts(
  username_hash TEXT PRIMARY KEY, attempts INTEGER NOT NULL, window_start BIGINT NOT NULL);

CREATE INDEX IF NOT EXISTS idx_lots_med ON lots(medicine_id, expiry);
CREATE INDEX IF NOT EXISTS idx_sales_date ON sales(created_at);
CREATE INDEX IF NOT EXISTS idx_sale_lines_sale ON sale_lines(sale_id);
CREATE INDEX IF NOT EXISTS idx_allocations_line ON sale_allocations(line_id);
CREATE INDEX IF NOT EXISTS idx_sale_payments_sale ON sale_payments(sale_id);
CREATE INDEX IF NOT EXISTS idx_orders_supplier ON orders(supplier_id);
CREATE INDEX IF NOT EXISTS idx_order_lines_order ON order_lines(order_id);
CREATE INDEX IF NOT EXISTS idx_invoice_supplier ON supplier_invoices(supplier_id);
CREATE INDEX IF NOT EXISTS idx_supplier_payments_invoice ON supplier_payments(invoice_id);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

INSERT INTO settings(key,value) VALUES
  ('clinic_name','VetStock'), ('clinic_address',''), ('clinic_phone',''),
  ('clinic_tax_id',''), ('backup_dir',''), ('last_backup','')
ON CONFLICT(key) DO NOTHING;

-- The browser receives no database credentials. The server uses its own secret connection.
REVOKE ALL ON ALL TABLES IN SCHEMA vetstock FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA vetstock FROM PUBLIC, anon, authenticated;
